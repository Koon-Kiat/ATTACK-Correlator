# Rebuild from decoded evidence only: file-input host/path and runtime timestamps
# must not become source telemetry. Dataset commands are never interpreted.
def filter(event)
  begin
    payload = LogStash::Json.load(event.get("message"))
    raise "expected one JSON object" unless payload.is_a?(Hash)
    id = payload.dig("event", "id")
    raise "missing or invalid Phase 3 event.id" unless id.is_a?(String) && id.match?(/\A[0-9a-f]{64}\z/)
    quality = payload.dig("windows_apt", "quality", "timestamp")
    if quality == "unresolved"
      raise "unresolved event contains @timestamp" if payload.key?("@timestamp")
    elsif quality == "explicit_utc"
      timestamp = payload["@timestamp"]
      raise "missing explicit UTC timestamp" unless timestamp.is_a?(String) && timestamp.end_with?("Z")
      # java.time preserves all available nanoseconds; no float/date-filter conversion.
      java.time.Instant.parse(timestamp)
    else
      raise "unsupported Phase 3 timestamp quality"
    end
    result = LogStash::Event.new(payload)
    result.remove("@version")
    result.remove("@timestamp") if quality == "unresolved"
    raise "timestamp parse failure" if result.get("_@timestamp") || result.get("tags")
    [result]
  rescue StandardError => error
    # Retain the complete input and reason outside the evidence index.
    event.set("[@metadata][phase4_rejected]", true)
    event.set("phase4_rejection_reason", error.message)
    [event]
  end
end

test "nanoseconds and original nested evidence survive" do
  in_event do
    { "message" => LogStash::Json.dump({
      "event" => { "id" => "a" * 64 },
      "@timestamp" => "2025-01-01T00:00:00.123456789Z",
      "windows_apt" => { "quality" => { "timestamp" => "explicit_utc" },
        "original" => { "literal.dotted" => "  C:\\example\\file  " } }
    }) }
  end
  expect("retains nanoseconds without input decorations") do |events|
    e = events.first
    e.get("@timestamp").to_s == "2025-01-01T00:00:00.123456789Z" &&
      e.get("[event][id]") == "a" * 64 &&
      e.get("[windows_apt][original][literal.dotted]") == "  C:\\example\\file  " &&
      e.get("@version").nil? && e.get("message").nil?
  end
end

test "missing deterministic document ID is rejected" do
  in_event do
    { "message" => '{"windows_apt":{"quality":{"timestamp":"unresolved"}}}' }
  end
  expect("visible rejection instead of an autogenerated Elasticsearch ID") do |events|
    events.first.get("[@metadata][phase4_rejected]") == true
  end
end

test "unresolved has no generated timestamp" do
  in_event do
    { "message" => '{"event":{"id":"' + "b" * 64 +
      '"},"windows_apt":{"quality":{"timestamp":"unresolved"}}}' }
  end
  expect("no @timestamp") do |events|
    events.first.get("@timestamp").nil? && events.first.get("@version").nil?
  end
end

test "malformed input remains visible" do
  in_event { { "message" => "{invalid" } }
  expect("routed to rejection file") do |events|
    events.first.get("[@metadata][phase4_rejected]") == true &&
      events.first.get("message") == "{invalid"
  end
end

test "contradictory unresolved timestamp is rejected" do
  in_event do
    { "message" => LogStash::Json.dump({ "event" => { "id" => "c" * 64 },
      "@timestamp" => "2025-01-01T00:00:00Z",
      "windows_apt" => { "quality" => { "timestamp" => "unresolved" } } }) }
  end
  expect("visible rejection") { |events| events.first.get("[@metadata][phase4_rejected]") }
end
