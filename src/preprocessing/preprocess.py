"""Verified, streaming Phase 3 preprocessing. No ingestion, detections or raw writes."""

import argparse
import csv
import hashlib
import json
import os
import platform
from collections import Counter
from pathlib import Path
from uuid import uuid4

from src.preprocessing.clean import csv_rows, nonempty, original_fields, restore_row
from src.preprocessing.elastic_contract import mapping_contract, validate_document
from src.preprocessing.enrich import annotate, build_join
from src.preprocessing.normalize import normalize, put
from src.preprocessing.profile_values import canonical

VERSION = "1.0.0"


def digest(path):
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def write_json(path, value):
    path.write_text(
        json.dumps(value, ensure_ascii=False, sort_keys=True, indent=2) + "\n",
        encoding="utf-8",
        newline="\n",
    )


def verify_sources(raw, expected):
    actual = {}
    for path in sorted(raw.rglob("*")):
        if path.is_file() and path.name != ".gitkeep":
            if path.is_symlink() or not path.resolve().is_relative_to(raw.resolve()):
                raise ValueError("Raw file escapes verified source tree")
            actual[path.relative_to(raw).as_posix()] = digest(path)
    mismatches = sorted(k for k in set(actual) | set(expected) if actual.get(k) != expected.get(k))
    if mismatches:
        raise ValueError("Phase 2 source hash mismatch: " + ", ".join(mismatches))
    if not actual:
        raise ValueError("No verified raw files")
    return actual


def leaf_fields(document, prefix=""):
    for name, value in document.items():
        field = prefix + name
        if isinstance(value, dict):
            yield from leaf_fields(value, field + ".")
        else:
            yield field


def provenance(row, source, row_index, end_line, source_hash):
    return {
        "source_file": source,
        "source_row_index": row_index,
        "csv_record_end_line": end_line,
        "source_sha256": source_hash,
        "original_index": row.get("_index", ""),
        "original_id": row.get("_id", ""),
        "source_representation": "period_csv",
        "dataset": "Windows-APT 2025",
        "dataset_version": "4",
        "processing_version": VERSION,
        "row_sha256": hashlib.sha256(canonical(row)).hexdigest(),
    }


def rejected_record(prov, reason, error, row, values):
    return {
        "provenance": prov,
        "rejection_reason": reason,
        "parsing_error": error,
        "original_fields": row,
        "parsed_csv_values": values,
    }


def render_report(summary):
    from src.preprocessing.inventory_reports import table

    c = summary["counts"]
    parts = [
        "# Phase 3 preprocessing report\n",
        "Generated by `python -m src.preprocessing.preprocess`. All counts describe this run. "
        "No dataset was ingested and no detection was evaluated.\n",
        table(["Record accounting", "Count"], sorted(c.items())),
        f"Record conservation: **{summary['record_conservation']['passed']}**. "
        "Every input row has one output or one explicit rejection; duplicate rows are retained.\n",
        "## Timestamp quality\n",
        table(["Quality", "Events"], sorted(summary["timestamp_quality"].items())),
        "Only a valid explicit Windows systemTime supplies @timestamp. Fractional digits "
        "are preserved up to nanoseconds. No fallback timezone or numeric-date conversion "
        "is guessed. Unresolved events remain in the output without @timestamp.\n",
        "## ECS field coverage\n",
        table(["Field", "Events populated"], sorted(summary["ecs_fields_populated"].items())),
        "## Normalization warnings\n",
        table(["Code", "Occurrences"], sorted(summary["normalization_warning_counts"].items())),
        "## Mapping warnings\n",
        table(["Code", "Occurrences"], sorted(summary["mapping_warning_counts"].items())),
        "Warnings count affected field observations; one event can have several warnings. "
        "Invalid and unmapped values remain in original evidence.\n",
        "## Scenario and annotation coverage\n",
        table(["Coverage", "Events"], sorted(summary["enrichment"].items())),
        table(["Attribution strength", "Events"], sorted(summary["scenario_strengths"].items())),
        "Scenario assignments are derived context, not independent malicious/benign truth. "
        "ATT&CK arrays and Wazuh metadata remain isolated from observable ECS fields.\n",
        "## Source files\n",
        table(
            ["Source", "Input", "Processed", "Rejected"],
            [
                (name, v["input"], v["processed"], v["rejected"])
                for name, v in sorted(summary["source_files"].items())
            ],
        ),
        "## Reproducibility and limits\n",
        "normalization-manifest.json records source/code/configuration/output/report hashes. "
        "The offline elastic-mapping.json contract uses date_nanos and disables parsing "
        "of original payloads, preventing arbitrary source columns from expanding mappings. "
        "Every output was checked against that local contract; actual Elasticsearch "
        "acceptance remains Phase 4 work. Use ordinary indices for unresolved timestamps; "
        "do not let Logstash substitute its current time.\n",
        "Original fields omit only exact empty CSV cells; source-schemas.json records "
        "every header in order so restore_row can reconstruct every original parsed row. "
        "Publisher metadata is retained in publisher-metadata.json; full per-row source "
        "mapping values remain under windows_apt.scenario.source_mapping.\n",
    ]
    return "\n".join(parts) + "\n"


def preprocess(
    raw=Path("dataset/raw"), output=Path("dataset/processed"), analysis=Path("analysis")
):
    raw, output, analysis = raw.resolve(), output.resolve(), analysis.resolve()
    if (
        output.is_relative_to(raw)
        or raw.is_relative_to(output)
        or analysis.is_relative_to(raw)
        or raw.is_relative_to(analysis)
        or output == analysis
    ):
        raise ValueError("Raw, output and analysis locations must be separate")
    phase2_path = analysis / "inventory-manifest.json"
    phase2 = json.loads(phase2_path.read_text(encoding="utf-8"))
    for name in ["attack_evidence.json", "dataset_schema.json", "ecs_mapping_candidates.md"]:
        if digest(analysis / name) != phase2["output_sha256"][name]:
            raise ValueError(f"Phase 2 artifact hash mismatch: {name}")
    source_hashes = verify_sources(raw, phase2["input_sha256"])
    evidence = json.loads((analysis / "attack_evidence.json").read_text(encoding="utf-8"))
    corpus = evidence["corpus"]
    root = raw / corpus["release_root_relative_to_raw"]
    sources = corpus["source_file_counts"]
    if "combined.csv" in sources or any(Path(s).name != s for s in sources):
        raise ValueError("Canonical corpus must contain only verified period filenames")
    if not root.resolve().is_relative_to(raw):
        raise ValueError("Canonical root escapes raw tree")
    code_hashes = {p.name: digest(p) for p in sorted(Path(__file__).parent.glob("*.py"))}
    output.mkdir(parents=True, exist_ok=True)
    analysis.mkdir(parents=True, exist_ok=True)
    stage = output / (".normalization-staging-" + uuid4().hex)
    stage.mkdir()
    database = stage / "scenario-index.sqlite"
    print("Verified raw hashes; building the disk-backed scenario join...", flush=True)
    connection, mapping_count, publisher = build_join(root, database)
    counts = Counter(
        input_events=0,
        processed_events=0,
        rejected_events=0,
        exact_duplicate_documents=0,
        conflicting_source_identities=0,
        invalid_ip_values=0,
        invalid_port_values=0,
        invalid_pid_values=0,
    )
    timestamps = Counter(explicit_utc=0, validated_fallback=0, unresolved=0)
    enrichment = Counter(
        mapping_join_matches=0,
        missing_mapping_rows=0,
        scenario_enriched_events=0,
        attack_annotated_events=0,
        wazuh_annotated_events=0,
    )
    fields, warnings, mapping_warnings, strengths = Counter(), Counter(), Counter(), Counter()
    identities, per_file, schemas = {}, {}, {}
    contract = mapping_contract()
    try:
        with (
            (stage / "windows-apt-events.ndjson").open("wb") as events_out,
            (stage / "rejected-events.ndjson").open("wb") as rejects_out,
        ):
            for source, expected_count in sorted(sources.items()):
                source_path = root / source
                relative = source_path.relative_to(raw).as_posix()
                file_counts = Counter(input=0, processed=0, rejected=0)
                for headers, index, end_line, row, values, error in csv_rows(source_path):
                    schemas[relative] = headers
                    counts["input_events"] += 1
                    file_counts["input"] += 1
                    prov = provenance(row, relative, index, end_line, source_hashes[relative])
                    found = connection.execute(
                        "SELECT 1 FROM mapping WHERE source=? AND n=?", (source, index)
                    ).fetchone()
                    enrichment["mapping_join_matches" if found else "missing_mapping_rows"] += 1
                    identity = (row.get("_index", ""), row.get("_id", ""))
                    signature = hashlib.sha256(canonical(original_fields(row))).hexdigest()
                    duplicate = identity in identities and identities[identity] == signature
                    if identity in identities:
                        counts[
                            "exact_duplicate_documents"
                            if duplicate
                            else "conflicting_source_identities"
                        ] += 1
                    identities.setdefault(identity, signature)
                    if error or not all(nonempty(v) for v in identity):
                        rejection = rejected_record(
                            prov,
                            "malformed_csv_row" if error else "missing_source_identity",
                            error or "Required _index or _id is empty",
                            row,
                            values,
                        )
                        rejects_out.write(canonical(rejection) + b"\n")
                        counts["rejected_events"] += 1
                        file_counts["rejected"] += 1
                        continue
                    event = normalize(row)
                    original = original_fields(row)
                    if restore_row(original, headers) != row:
                        raise ValueError("Original row round-trip failed")
                    put(event, "windows_apt.original", original)
                    put(event, "windows_apt.provenance", prov)
                    put(
                        event,
                        "event.id",
                        hashlib.sha256(
                            canonical([relative, index, source_hashes[relative]])
                        ).hexdigest(),
                    )
                    annotations, scenario, annotation_warnings = annotate(
                        row,
                        source,
                        index,
                        connection,
                        {r["Scenrario_ID"] for r in publisher["manifest"]},
                    )
                    quality = event["windows_apt"]["quality"]
                    if annotation_warnings:
                        quality.setdefault("normalization_warnings", []).extend(annotation_warnings)
                    if duplicate:
                        quality.setdefault("mapping_warnings", []).append(
                            {"field": "_index/_id", "code": "exact_duplicate_retained"}
                        )
                    if annotations:
                        put(event, "windows_apt.annotations", annotations)
                        enrichment["attack_annotated_events"] += bool(
                            annotations.get("attack", {}).get("ids")
                        )
                        enrichment["wazuh_annotated_events"] += bool(annotations.get("wazuh"))
                    if scenario:
                        put(event, "windows_apt.scenario", scenario)
                        enrichment["scenario_enriched_events"] += 1
                        strengths[scenario.get("attribution_strength", "(missing)")] += 1
                    for category in ["normalization_warnings", "mapping_warnings"]:
                        if category in quality:
                            quality[category].sort(key=lambda item: (item["field"], item["code"]))
                    validate_document(event, contract)
                    events_out.write(canonical(event) + b"\n")
                    counts["processed_events"] += 1
                    file_counts["processed"] += 1
                    timestamps[quality["timestamp"]] += 1
                    fields.update(f for f in leaf_fields(event) if not f.startswith("windows_apt."))
                    warnings.update(w["code"] for w in quality.get("normalization_warnings", []))
                    mapping_warnings.update(w["code"] for w in quality.get("mapping_warnings", []))
                if file_counts["input"] != expected_count:
                    raise ValueError(f"Phase 2 row count changed: {source}")
                per_file[source] = dict(file_counts)
                print(
                    f"Processed {source}: {file_counts['processed']} events, "
                    f"{file_counts['rejected']} rejects",
                    flush=True,
                )
    finally:
        connection.close()
    counts["distinct_source_identities"] = len(identities)
    for kind, keys in {
        "ip": ["invalid_source_ip", "invalid_destination_ip"],
        "port": ["invalid_source_port", "invalid_destination_port"],
        "pid": ["invalid_process_pid", "invalid_process_parent_pid"],
    }.items():
        counts["invalid_" + kind + "_values"] = sum(warnings[k] for k in keys)
    if (
        counts["input_events"] != corpus["exported_rows"]
        or len(identities) != corpus["coverage_events"]
    ):
        raise ValueError("Canonical count differs from Phase 2")
    if mapping_count != enrichment["mapping_join_matches"] or enrichment["missing_mapping_rows"]:
        raise ValueError("Scenario join does not cover the canonical corpus exactly")
    conserved = counts["input_events"] == counts["processed_events"] + counts["rejected_events"]
    if not conserved:
        raise ValueError("Record conservation failed")
    verify_sources(raw, source_hashes)
    if code_hashes != {p.name: digest(p) for p in sorted(Path(__file__).parent.glob("*.py"))}:
        raise ValueError("Preprocessing code changed during the run")
    summary = {
        "phase": 3,
        "processing_version": VERSION,
        "counts": dict(counts),
        "timestamp_quality": dict(timestamps),
        "ecs_fields_populated": dict(fields),
        "normalization_warning_counts": dict(warnings),
        "mapping_warning_counts": dict(mapping_warnings),
        "enrichment": dict(enrichment),
        "scenario_strengths": dict(strengths),
        "source_files": per_file,
        "record_conservation": {
            "passed": conserved,
            "raw_files_unchanged": True,
            "original_rows_round_tripped": counts["processed_events"],
        },
    }
    write_json(
        stage / "source-schemas.json",
        {"empty_cell_policy": "Absent key means exact empty CSV cell", "headers": schemas},
    )
    write_json(stage / "publisher-metadata.json", publisher)
    write_json(stage / "elastic-mapping.json", contract)
    write_json(stage / "preprocessing_summary.json", summary)
    (stage / "preprocessing_report.md").write_text(
        render_report(summary), encoding="utf-8", newline="\n"
    )
    output_names = [
        "windows-apt-events.ndjson",
        "source-schemas.json",
        "publisher-metadata.json",
        "elastic-mapping.json",
    ]
    if counts["rejected_events"]:
        output_names.append("rejected-events.ndjson")
    else:
        (stage / "rejected-events.ndjson").unlink()
    report_names = ["preprocessing_summary.json", "preprocessing_report.md"]
    manifest = {
        "phase": 3,
        "phase2_manifest_sha256": digest(phase2_path),
        "phase2_source_sha256": source_hashes,
        "phase2_artifact_sha256": phase2["output_sha256"],
        "preprocessing_source_sha256": code_hashes,
        "configuration": {
            "processing_version": VERSION,
            "python_version": platform.python_version(),
            "encoding": "utf-8-sig",
            "output_encoding": "utf-8",
            "newline": "LF",
            "timestamp_fallback": "none",
            "duplicates": "retain",
            "canonical_files": sorted(sources),
        },
        "processed_output_sha256": {name: digest(stage / name) for name in output_names},
        "report_sha256": {name: digest(stage / name) for name in report_names},
        "counts": dict(counts),
    }
    # Publish only completed files. The manifest is the last-written commit marker.
    for name, directory in [(n, output) for n in output_names] + [
        (n, analysis) for n in report_names
    ]:
        target = directory / name
        if target.is_symlink() or not target.resolve().is_relative_to(directory):
            raise ValueError("Output target escapes destination")
        os.replace(stage / name, target)
    stale_reject = output / "rejected-events.ndjson"
    if not counts["rejected_events"] and stale_reject.exists():
        if stale_reject.is_symlink():
            raise ValueError("Refusing symlink rejection output")
        stale_reject.unlink()
    write_json(stage / "normalization-manifest.json", manifest)
    os.replace(stage / "normalization-manifest.json", analysis / "normalization-manifest.json")
    database.unlink()
    stage.rmdir()
    print(
        f"Conserved {counts['input_events']} inputs = {counts['processed_events']} processed "
        f"+ {counts['rejected_events']} rejected",
        flush=True,
    )
    return summary


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=Path("dataset/raw"))
    parser.add_argument("--output", type=Path, default=Path("dataset/processed"))
    parser.add_argument("--analysis", type=Path, default=Path("analysis"))
    args = parser.parse_args()
    try:
        preprocess(args.input, args.output, args.analysis)
    except (OSError, ValueError, csv.Error, KeyError) as error:
        parser.exit(1, f"Preprocessing stopped: {error}\n")


if __name__ == "__main__":
    main()
